using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json.Nodes;
using System.Xml.Linq;
using NeoGameLib.NeoMapping;

namespace NeoGameLib.NeoUI;

// note to future self:
// two outputs, ONE source (NeoUIDocument.Describe/DescribeLayout, which reads the same binding table the loader uses, with defaults from fresh instances):
//   - Build():    the `x-neo-ui` section of <Game>.neoschema.json, what the editor builds its panels from
//   - BuildXsd(): Data/<Game>.neoui.xsd, what IDEs use for completion and checking while you hand-edit
// so the editor's panels, the IDE's squiggles and the loader can't drift apart.
//
// what XSD 1.0 can NOT say, and the loader / editor check instead:
//   - "width OR left/right, not both": which form is valid depends on whether the anchors differ, a value-dependent rule
//   - the shape of the value strings (colors, vectors, ...). they ARE patterns below, but a pattern only checks the shape, not e.g. that an anchor stays within 0-1
// the XSD is generated per game (it lists the game's own actions), a built-ins-only copy for people without the tool is generated by the same code with no assembly scanned.
internal static class NeoUISchema
{
    private const string Xs = "http://www.w3.org/2001/XMLSchema";
    private static readonly XNamespace X = Xs;

    // value patterns; they check the SHAPE only. a float is any decimal number, an int a whole number
    private const string Num = @"[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?";
    private static readonly Dictionary<string, string> Patterns = new()
    {
        ["float"] = Num,
        ["int"] = @"[+-]?\d+",
        ["vector2"] = $@"\s*{Num}(\s+{Num})?\s*",
        ["color"] = @"#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})",
        ["padding"] = $@"\s*{Num}(\s+{Num}(\s+{Num}\s+{Num})?)?\s*",
        ["rect"] = @"\s*[+-]?\d+(\s+[+-]?\d+){3}\s*",
    };

    private static readonly string[] Docs =
    {
        "float", "int", "vector2", "color", "padding", "rect", "anchor",
    };

    // ---- x-neo-ui ----

    internal static JsonObject Build()
    {
        JsonObject elements = new();
        foreach (NeoUIDocument.UIElementInfo element in NeoUIDocument.Describe())
            elements[element.Name] = new JsonObject
            {
                ["attributes"] = new JsonArray(element.Attributes.Select(Attribute).ToArray()),
                ["base"] = element.Name == "FlexBox" ? "Panel" : null,
                ["children"] = element.Name is "Canvas" or "Panel" or "FlexBox",
                ["layout"] = element.Name != "Canvas", // a canvas always covers the viewport; layout attributes on it are a load error
            };

        JsonObject types = new();
        foreach (string name in Docs) types[name] = ValueDoc(name);

        return new JsonObject
        {
            ["namespace"] = NeoUIDocument.Namespace,
            ["extension"] = NeoUIDocument.Extension,
            ["folder"] = $"{NeoProject.DataFolder}/{NeoProject.UIFolder}",
            ["root"] = "Canvas",
            ["elements"] = elements,
            ["layout"] = new JsonArray(NeoUIDocument.DescribeLayout().Select(Attribute).ToArray()),
            ["anchorPresets"] = new JsonArray(NeoUIValues.AnchorPresets.Select(p => (JsonNode) new JsonObject
            {
                ["name"] = p.Name,
                ["anchorMin"] = new JsonObject { ["x"] = p.Min.X, ["y"] = p.Min.Y },
                ["anchorMax"] = new JsonObject { ["x"] = p.Max.X, ["y"] = p.Max.Y },
            }).ToArray()),
            ["types"] = types,
            ["onClickActions"] = "Button.onClick",
            ["builtinFont"] = BuiltinFont(),
        };
    }

    // the editor ships its own copy of Inter.xnb to preview text; the hash lets it warn when its copy isn't the one in this library version
    private static JsonObject BuiltinFont()
    {
        using Stream stream = typeof(NeoUISchema).Assembly.GetManifestResourceStream("NeoGameLib.Builtin.Inter.xnb") ?? throw new InvalidOperationException("the embedded Inter.xnb is missing from NeoGameLib.dll");
        
        return new JsonObject
        {
            ["name"] = "Inter",
            ["file"] = "Inter.xnb",
            ["sha256"] = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(stream)).ToLowerInvariant(),
        };
    }

    private static JsonNode Attribute(NeoUIDocument.UIAttributeInfo a)
    {
        JsonObject node = new() { ["name"] = a.Name, ["type"] = a.Type };
        
        if (a.Default is not null) node["default"] = a.Default;
        if (a.EnumValues is not null) node["enum"] = new JsonArray(a.EnumValues.Select(v => (JsonNode)v).ToArray());
        if (a.Asset is not null) node["x-neo-asset"] = a.Asset;
        
        return node;
    }

    private static JsonObject ValueDoc(string type) => type switch
    {
        "float" => new JsonObject { ["description"] = "a decimal number, '.' as the separator" },
        "int" => new JsonObject { ["description"] = "a whole number" },
        "vector2" => new JsonObject { ["description"] = "\"x y\", or one number for both" },
        "color" => new JsonObject { ["description"] = "#RRGGBB or #RRGGBBAA, raw RGBA as MonoGame's Color stores it (premultiplied); alpha defaults to FF" },
        "padding" => new JsonObject { ["description"] = "\"all\", \"horizontal vertical\" or \"left top right bottom\"" },
        "rect" => new JsonObject { ["description"] = "\"x y width height\" in whole pixels" },
        "anchor" => new JsonObject { ["description"] = "a preset name, \"x y\" (a point) or \"minX minY maxX maxY\" (a range)" },
        _ => new JsonObject(),
    };

    // ---- the XSD ----

    /// <summary>Generates the XSD. actionNames come from the registry (built-ins plus the game's own), so hand-written actions get checked too.</summary>
    internal static string BuildXsd()
    {
        XElement schema = new(X + "schema",
            new XAttribute("targetNamespace", NeoUIDocument.Namespace),
            new XAttribute("xmlns", NeoUIDocument.Namespace),
            new XAttribute("elementFormDefault", "qualified"),
            new XAttribute("attributeFormDefault", "unqualified"),
            new XAttribute(XNamespace.Xmlns + "xs", Xs),
            new XComment(" generated by the NeoGameLib schema tool from the same table the loader uses, do not edit by hand "));

        foreach ((string name, string pattern) in Patterns)
            schema.Add(Simple(name, pattern));
        schema.Add(AnchorType());
        schema.Add(Simple("bool", "true|false"));

        // enums shared by name (NeoUISizing is used by every element's layout attributes)
        Dictionary<string, string[]> enums = new();
        foreach (NeoUIDocument.UIAttributeInfo a in NeoUIDocument.DescribeLayout().Concat(NeoUIDocument.Describe().SelectMany(e => e.Attributes)))
            if (a.EnumName is not null && a.EnumValues is not null) enums[a.EnumName] = a.EnumValues;
        foreach ((string name, string[] values) in enums.OrderBy(e => e.Key, StringComparer.Ordinal))
            schema.Add(new XElement(X + "simpleType", new XAttribute("name", name),
                new XElement(X + "restriction", new XAttribute("base", "xs:string"), values.Select(v => new XElement(X + "enumeration", new XAttribute("value", v))))));

        // layout attributes every element has
        schema.Add(new XElement(X + "attributeGroup", new XAttribute("name", "layout"), NeoUIDocument.DescribeLayout().Select(a => AttributeDecl(a, false))));

        // a group of the elements that can appear as children (everything but Canvas), then one complexType per element
        List<NeoUIDocument.UIElementInfo> elements = NeoUIDocument.Describe();
        string[] childNames = elements.Where(e => e.Name != "Canvas").Select(e => e.Name).ToArray();
        schema.Add(new XElement(X + "group", new XAttribute("name", "children"),
            new XElement(X + "choice",
                childNames.Select(n => new XElement(X + "element", new XAttribute("name", n), new XAttribute("type", n))))));

        foreach (NeoUIDocument.UIElementInfo element in elements)
        {
            bool container = element.Name is "Canvas" or "Panel" or "FlexBox";
            XElement type = new(X + "complexType", new XAttribute("name", element.Name));

            if (container) type.Add(new XElement(X + "group", new XAttribute("ref", "children"), new XAttribute("minOccurs", "0"), new XAttribute("maxOccurs", "unbounded")));
            else if (element.Name == "Button") type.Add(ButtonContent());

            if (element.Name != "Canvas") type.Add(new XElement(X + "attributeGroup", new XAttribute("ref", "layout")));
            
            foreach (NeoUIDocument.UIAttributeInfo a in element.Attributes)
            {
                type.Add(AttributeDecl(a, false));
            }
            
            schema.Add(type);
        }

        schema.Add(new XElement(X + "element", new XAttribute("name", "Canvas"), new XAttribute("type", "Canvas")));

        // actions: a choice of the registered ones. properties are attributes (scalars) and <Action.property> elements (lists/records), which the generic xs:any lets through; the registry validates them when the file loads
        schema.Add(ActionDefinitions().Cast<object>().ToArray());

        return new XDocument(new XDeclaration("1.0", "utf-8", null), schema).ToString() + "\n";
    }

    private static XElement Simple(string name, string pattern) =>
        new(X + "simpleType", new XAttribute("name", name),
            new XElement(X + "restriction", new XAttribute("base", "xs:string"), new XElement(X + "pattern", new XAttribute("value", pattern))));

    private static XElement AnchorType()
    {
        string presets = string.Join("|", NeoUIValues.AnchorPresets.Select(p => p.Name));
        string four = $@"\s*{Num}(\s+{Num}){{1,3}}\s*"; // a point (2 numbers) or a range (4); a count of 3 is rejected at load
        return Simple("anchor", $"{presets}|{four}");
    }

    private static XElement AttributeDecl(NeoUIDocument.UIAttributeInfo a, bool required)
    {
        string type = a.Type switch
        {
            "string" => "xs:string",
            "enum" => a.EnumName!,
            _ => a.Type,
        };
        
        XElement decl = new(X + "attribute", new XAttribute("name", a.Name), new XAttribute("type", type));
        
        if (required) 
            decl.Add(new XAttribute("use", "required"));
        
        return decl;
    }

    // <Button.onClick> holds a choice of actions, declared by ActionDefinitions
    private static XElement ButtonContent() =>
        new(X + "sequence",
            new XElement(X + "element", new XAttribute("name", "Button.onClick"), new XAttribute("minOccurs", "0"),
                new XElement(X + "complexType",
                    new XElement(X + "group", new XAttribute("ref", "actions"), new XAttribute("minOccurs", "0"), new XAttribute("maxOccurs", "unbounded")))),
            new XElement(X + "group", new XAttribute("ref", "children"), new XAttribute("minOccurs", "0"), new XAttribute("maxOccurs", "unbounded")));

    // two top-level components: the shared open "action" type and the "actions" group that lists the registered action names
    private static IEnumerable<XElement> ActionDefinitions()
    {
        // an action element has free attributes and free property child elements (<Name.property>), so the type is open. the registry validates the properties when the file loads
        yield return new XElement(X + "complexType", new XAttribute("name", "action"),
            new XElement(X + "sequence", new XElement(X + "any", new XAttribute("minOccurs", "0"), new XAttribute("maxOccurs", "unbounded"), new XAttribute("processContents", "skip"))),
            new XElement(X + "anyAttribute", new XAttribute("processContents", "skip")));

        yield return new XElement(X + "group", new XAttribute("name", "actions"),
            new XElement(X + "choice",
                NeoRegistry.Actions.Keys.OrderBy(n => n, StringComparer.Ordinal)
                    .Select(n => new XElement(X + "element", new XAttribute("name", n), new XAttribute("type", "action")))));
    }
}
